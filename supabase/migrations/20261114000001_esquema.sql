-- Esquema de Tina para Supabase (Postgres).
-- Sigue el modelo entidad-relación del proyecto: una tabla por entidad, con los
-- mismos campos que las clases de lib/models/. Los precios van en pesos enteros.
-- Se agrega `ajuste_sitio` para las fotos del sitio que la administradora cambia
-- desde el panel.

-- ---------------------------------------------------------------- catálogo --

create table public.categoria (
  id_categoria bigint generated by default as identity primary key,
  nombre       text   not null,
  descripcion  text   not null default ''
);

create table public.producto (
  id_producto  bigint generated by default as identity primary key,
  id_categoria bigint  not null references public.categoria (id_categoria),
  nombre       text    not null,
  descripcion  text    not null default '',
  tecnica      text    not null default '',
  precio       integer not null check (precio >= 0),
  activo       boolean not null default true
);

-- `ruta` es el archivo dentro del bucket `productos`; `url` es su dirección
-- pública. `orden` 1 es la foto principal.
create table public.imagen_producto (
  id_imagen   bigint generated by default as identity primary key,
  id_producto bigint  not null references public.producto (id_producto) on delete cascade,
  url         text    not null,
  ruta        text    not null,
  orden       integer not null default 1 check (orden >= 1)
);

create table public.variante_producto (
  id_variante bigint generated by default as identity primary key,
  id_producto bigint  not null references public.producto (id_producto) on delete cascade,
  color       text    not null,
  talla       text    not null default 'Única',
  stock       integer not null default 0 check (stock >= 0),
  unique (id_producto, color, talla)
);

create table public.promocion (
  id_promocion    bigint generated by default as identity primary key,
  nombre          text    not null,
  tipo            text    not null check (tipo in ('primera_compra', 'volumen')),
  porcentaje      integer not null check (porcentaje between 1 and 100),
  cantidad_minima integer not null default 1 check (cantidad_minima >= 1),
  activa          boolean not null default true
);

-- ------------------------------------------------------------------ personas --

-- Quienes entran al panel. `id_auth` enlaza con la cuenta de Supabase Auth.
create table public.usuario (
  id_usuario bigint generated by default as identity primary key,
  id_auth    uuid unique references auth.users (id) on delete cascade,
  nombre     text not null,
  correo     text not null,
  rol        text not null check (rol in ('administradora', 'sistema'))
);

-- Las clientas sin cuenta también tienen fila, con cuenta_registrada en falso.
create table public.cliente (
  id_cliente                  bigint generated by default as identity primary key,
  id_auth                     uuid unique references auth.users (id) on delete set null,
  nombre                      text        not null,
  correo                      text        not null,
  telefono                    text        not null default '',
  cuenta_registrada           boolean     not null default false,
  fecha_registro              timestamptz not null default now(),
  fecha_ultimo_inicio_sesion  timestamptz
);

-- ------------------------------------------------------------------- carrito --

create table public.carrito (
  id_carrito          bigint generated by default as identity primary key,
  id_cliente          bigint references public.cliente (id_cliente),
  token_sesion        text        not null,
  estado              text        not null default 'abierto',
  fecha_creacion      timestamptz not null default now(),
  fecha_actualizacion timestamptz not null default now(),
  fecha_recordatorio  timestamptz
);

create table public.carrito_item (
  id_item     bigint generated by default as identity primary key,
  id_carrito  bigint  not null references public.carrito (id_carrito) on delete cascade,
  id_variante bigint  not null references public.variante_producto (id_variante),
  cantidad    integer not null check (cantidad >= 1),
  unique (id_carrito, id_variante)
);

-- ------------------------------------------------------------------- pedidos --

-- total = subtotal - descuento. El envío va aparte, en la tabla `envio`.
create table public.pedido (
  id_pedido     bigint generated by default as identity primary key,
  id_cliente    bigint      not null references public.cliente (id_cliente),
  id_promocion  bigint      references public.promocion (id_promocion),
  fecha         timestamptz not null default now(),
  estado_actual text        not null default 'pendiente'
    check (estado_actual in ('pendiente', 'pagado', 'preparacion', 'enviado', 'entregado', 'cancelado')),
  subtotal      integer     not null check (subtotal >= 0),
  descuento     integer     not null default 0 check (descuento >= 0),
  total         integer     not null check (total >= 0)
);

-- El precio unitario se copia al comprar: un cambio de precio posterior no
-- altera pedidos anteriores.
create table public.detalle_pedido (
  id_detalle      bigint generated by default as identity primary key,
  id_pedido       bigint  not null references public.pedido (id_pedido) on delete cascade,
  id_variante     bigint  not null references public.variante_producto (id_variante),
  cantidad        integer not null check (cantidad >= 1),
  precio_unitario integer not null check (precio_unitario >= 0),
  subtotal        integer not null check (subtotal >= 0)
);

create table public.pago (
  id_pago          bigint generated by default as identity primary key,
  id_pedido        bigint      not null references public.pedido (id_pedido),
  referencia_wompi text        not null,
  monto            integer     not null check (monto >= 0),
  estado           text        not null default 'pendiente'
    check (estado in ('pendiente', 'aprobado', 'rechazado')),
  fecha            timestamptz not null default now()
);

-- Un pago aprobado genera un solo comprobante.
create table public.comprobante (
  id_comprobante bigint generated by default as identity primary key,
  id_pago        bigint      not null unique references public.pago (id_pago),
  numero         text        not null unique,
  fecha_emision  timestamptz not null default now()
);

create table public.envio (
  id_envio            bigint generated by default as identity primary key,
  id_pedido           bigint  not null unique references public.pedido (id_pedido) on delete cascade,
  nombre_destinatario text    not null,
  telefono            text    not null,
  departamento        text    not null,
  ciudad              text    not null,
  direccion           text    not null,
  costo               integer not null default 0 check (costo >= 0),
  guia                text
);

create table public.historial_estado (
  id_historial    bigint generated by default as identity primary key,
  id_pedido       bigint      not null references public.pedido (id_pedido) on delete cascade,
  id_usuario      bigint      not null references public.usuario (id_usuario),
  estado_anterior text,
  estado_nuevo    text        not null,
  notificado      boolean     not null default false,
  fecha           timestamptz not null default now()
);

-- -------------------------------------------------------- fotos del sitio --

-- Un lugar de la página con nombre (la portada, el logo...) y la foto que tiene
-- ahora. `url` y `ruta` quedan vacías hasta que la administradora sube una;
-- mientras tanto la app muestra su diseño por defecto.
create table public.ajuste_sitio (
  clave       text primary key,
  descripcion text        not null,
  url         text,
  ruta        text,
  actualizado timestamptz not null default now()
);

-- ----------------------------------------------------------------- índices --

create index on public.producto (id_categoria);
create index on public.imagen_producto (id_producto, orden);
create index on public.variante_producto (id_producto);
create index on public.pedido (id_cliente);
create index on public.detalle_pedido (id_pedido);
create index on public.historial_estado (id_pedido);
