-- Charm Bar, colecciones, suscripción por correo y lugares para fotos del sitio.
--
-- 1. Charm Bar: dos categorías nuevas ("Charm Bar" para el collar base y
--    "Charms" para las piezas que se le ponen) con productos de ejemplo
--    OCULTOS y sin stock. La vendedora les pone precio, stock y fotos desde el
--    panel y los muestra cuando estén listos.
-- 2. Colecciones: grupos de productos con nombre, subtítulo y foto.
-- 3. Suscripción: la función `suscribirse` guarda un correo (nadie puede leer la
--    lista, solo la administradora).
-- 4. Fotos del sitio: el banner del Charm Bar en la portada y la foto grande de
--    la página del Charm Bar.

-- ----------------------------------------------------------------- Charm Bar --

insert into public.categoria (nombre, descripcion)
select 'Charm Bar', 'Arma tu collar'
where not exists (select 1 from public.categoria where nombre = 'Charm Bar');

insert into public.categoria (nombre, descripcion)
select 'Charms', 'Charms para tu collar'
where not exists (select 1 from public.categoria where nombre = 'Charms');

do $$
declare
  v_base   bigint;
  v_charm  bigint;
  v_cat_cb bigint := (select id_categoria from public.categoria where nombre = 'Charm Bar');
  v_cat_ch bigint := (select id_categoria from public.categoria where nombre = 'Charms');
  v_color  text;
  v_talla  text;
  v_nombre text;
begin
  -- El collar base: un color de cuentas por cada modo de poner los charms.
  if not exists (select 1 from public.producto where id_categoria = v_cat_cb) then
    insert into public.producto (id_categoria, nombre, descripcion, tecnica, precio, activo)
    values (v_cat_cb, 'Collar Charm Bar',
            'El collar base de cuentas donde pones tus charms. Elige el color, el modo y los charms que quieras.',
            'Cuentas ensartadas a mano', 60000, false)
    returning id_producto into v_base;

    foreach v_color in array array['Palo rosa', 'Naranja', 'Blanco', 'Rosado'] loop
      foreach v_talla in array array['Charms fijos', 'Charms removibles'] loop
        insert into public.variante_producto (id_producto, color, talla, stock)
        values (v_base, v_color, v_talla, 0);
      end loop;
    end loop;
  end if;

  -- Los charms: cada uno es un producto con una sola variante.
  if not exists (select 1 from public.producto where id_categoria = v_cat_ch) then
    foreach v_nombre in array array[
      'Charm Corazón', 'Charm Flor', 'Charm Estrella', 'Charm Mariposa',
      'Charm Cereza', 'Charm Fresa', 'Charm Hongo', 'Charm Letra A'
    ] loop
      insert into public.producto (id_categoria, nombre, descripcion, tecnica, precio, activo)
      values (v_cat_ch, v_nombre, 'Charm hecho a mano para tu collar.', 'Porcelanicrón moldeado a mano', 12000, false)
      returning id_producto into v_charm;
      insert into public.variante_producto (id_producto, color, talla, stock)
      values (v_charm, 'Único', 'Única', 0);
    end loop;
  end if;
end;
$$;

-- --------------------------------------------------------------- colecciones --

create table if not exists public.coleccion (
  id_coleccion bigint generated by default as identity primary key,
  nombre       text    not null check (length(trim(nombre)) > 0),
  subtitulo    text    not null default '',
  orden        integer not null default 1,
  activa       boolean not null default true,
  url          text,
  ruta         text
);

alter table public.producto
  add column if not exists id_coleccion bigint
  references public.coleccion (id_coleccion) on delete set null;

create index if not exists producto_coleccion_idx on public.producto (id_coleccion);

alter table public.coleccion enable row level security;

drop policy if exists "ver colecciones activas" on public.coleccion;
create policy "ver colecciones activas" on public.coleccion
  for select using (activa or public.es_admin());

drop policy if exists "admin gestiona colecciones" on public.coleccion;
create policy "admin gestiona colecciones" on public.coleccion
  for all using (public.es_admin()) with check (public.es_admin());

grant select on public.coleccion to anon, authenticated;
grant insert, update, delete on public.coleccion to authenticated;

-- ---------------------------------------------------------------- suscripción --

create table if not exists public.suscripcion (
  id_suscripcion bigint generated by default as identity primary key,
  correo         text        not null unique,
  fecha          timestamptz not null default now()
);

alter table public.suscripcion enable row level security;

drop policy if exists "admin ve suscripciones" on public.suscripcion;
create policy "admin ve suscripciones" on public.suscripcion
  for select using (public.es_admin());

drop policy if exists "admin borra suscripciones" on public.suscripcion;
create policy "admin borra suscripciones" on public.suscripcion
  for delete using (public.es_admin());

-- Cualquiera puede suscribirse (con la función), nadie puede leer la lista.
create or replace function public.suscribirse(p_correo text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_correo text := lower(trim(coalesce(p_correo, '')));
begin
  if v_correo !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'Escribe un correo válido.';
  end if;
  insert into public.suscripcion (correo) values (v_correo)
  on conflict (correo) do nothing;
end;
$$;

revoke execute on function public.suscribirse(text) from public;
grant execute on function public.suscribirse(text) to anon, authenticated;

